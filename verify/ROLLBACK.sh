#!/usr/bin/env bash
# 红果桌面版补丁回滚脚本（可移植、自包含）
#
# 用法:
#   ./ROLLBACK.sh <目标文件>
#   ./ROLLBACK.sh --all <应用目录>
#
# 说明:
#   - 只接受显式给出的路径，绝不递归删除或批量扫描。
#   - 原始字节内嵌在本脚本末尾的 base64 区块中，
#     即使仓库里的 base/ 目录丢失也能还原。
#   - 还原前会先把现有文件备份为 <目标>.before-rollback，
#     便于再次前进（re-apply）。
set -euo pipefail

PAYLOAD_MARKER="__ROLLBACK_PAYLOAD__"

usage() {
  echo "用法: $0 <目标文件>" >&2
  echo "      $0 --all <应用目录>" >&2
  exit 2
}

# 从本脚本中取出指定角色的 base64 负载并还原到目标路径。
restore_role() {
  local role="$1" target="$2"
  local self="$3"
  if [ ! -f "$target" ]; then
    echo "[FAIL] 目标不存在: $target" >&2
    return 1
  fi
  local backup="${target}.before-rollback"
  cp -p "$target" "$backup"
  echo "[OK] 已备份当前文件 -> $backup"

  local tmp
  tmp="$(mktemp)"
  awk -v role="$role" -v marker="$PAYLOAD_MARKER" '
    $0 == marker ":" role { grab = 1; next }
    grab && /^#END/ { grab = 0; next }
    grab { print }
  ' "$self" | base64 -d > "$tmp"

  if [ ! -s "$tmp" ]; then
    rm -f "$tmp"
    echo "[FAIL] 未找到角色 $role 的内嵌基线" >&2
    return 1
  fi
  mv "$tmp" "$target"
  echo "[OK] 已还原 $target"
  echo "     sha256: $(sha256sum "$target" | cut -d' ' -f1)"
}

SELF="$0"

if [ "${1:-}" = "--all" ]; then
  [ $# -eq 2 ] || usage
  APP="$2"
  BACKEND="$APP/backend"
  [ -d "$BACKEND" ] || { echo "[FAIL] 未找到后端目录: $BACKEND" >&2; exit 1; }
  restore_role "desktop_hls_service.py" "$BACKEND/desktop_hls_service.py" "$SELF"
  restore_role "desktop_hls.py"         "$BACKEND/desktop_hls.py"         "$SELF"
  restore_role "desktop_encode.py"      "$BACKEND/desktop_encode.py"      "$SELF"
  restore_role "server.py"              "$BACKEND/server.py"              "$SELF"
  echo "[OK] 后端已全部还原为原版（exe 请另用 tools/restore.ps1 还原）"
  exit 0
fi

[ $# -eq 1 ] || usage
TARGET="$1"
case "$(basename "$TARGET")" in
  desktop_hls_service.py) ROLE="desktop_hls_service.py" ;;
  desktop_hls.py)         ROLE="desktop_hls.py" ;;
  desktop_encode.py)      ROLE="desktop_encode.py" ;;
  server.py)              ROLE="server.py" ;;
  *) echo "[FAIL] 不支持的文件名: $(basename "$TARGET")" >&2; exit 2 ;;
esac
restore_role "$ROLE" "$TARGET" "$SELF"

exit 0

